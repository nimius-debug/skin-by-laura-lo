#!/usr/bin/env python3
"""Regenerate src/admin/data/sheet-notes.js from the Excel review workbook.

Usage: python3 scripts/build-sheet-notes.py path/to/client-notes-review.xlsx

Reads the "All notes" tab and writes the four treatment fields for every row,
exactly as written in the sheet (line breaks kept). Keys are the note ids the
importer used: sheet_R<row>. Re-run this whenever the sheet changes.
"""
import json
import pathlib
import sys

import openpyxl

FIELDS = ["Treatment type", "Notes / remarks", "Purchase history", "Possible treatments"]

source = sys.argv[1]
out = pathlib.Path(__file__).resolve().parent.parent / "src/admin/data/sheet-notes.js"

sheet = openpyxl.load_workbook(source, read_only=True)["All notes"]
rows = sheet.iter_rows(values_only=True)
header = list(next(rows))
columns = {name: header.index(name) for name in ["Row ID", *FIELDS]}

notes = {}
for row in rows:
    row_id = row[columns["Row ID"]]
    if not row_id:
        continue
    fields = {}
    for name in FIELDS:
        value = row[columns[name]]
        if isinstance(value, str) and value.strip():
            fields[name] = value.rstrip()
    notes[f"sheet_{row_id}"] = fields

body = json.dumps(notes, ensure_ascii=False, indent=1)
out.write_text(
    "// Generated by scripts/build-sheet-notes.py from the Excel review sheet. Do not edit by hand.\n"
    "// Keys are the note ids the importer used (sheet_R<row>).\n"
    f"export const SHEET_NOTE_FIELDS = {body};\n",
    encoding="utf-8",
)
print(f"{len(notes)} notes written to {out}")
