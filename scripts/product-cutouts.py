#!/usr/bin/env python3
"""Cut the background out of every shop product photo, for the Skincare Guide PDFs.

    pip install "rembg[cpu]" pillow
    npm run products:list                      # product-list.json from Square
    python3 scripts/product-cutouts.py product-list.json

For each product photo (a Square image URL) it:
- downloads the photo and removes the background (rembg; the model is
  downloaded the first time, about 180 MB),
- trims the empty space, shrinks it to at most 900 px tall and saves it as a
  transparent WebP in public/media/products/cutouts/<photo id>.webp,
- checks the result and flags the ones to look at (part of the product lost,
  backdrop left in, soft halo edges, product cut at the photo's edge),
- writes src/data/product-cutouts.data.js (which photos have a cut-out) and a
  contact sheet of every cut-out on the guide's beige, to check by eye.

Photos that already have a cut-out are skipped unless --redo is given, so it
can be run again whenever products are added. --skip <photo id> leaves a photo
out (its guide keeps the original). Nothing is sent anywhere: rembg runs locally.
"""
import argparse, io, json, os, re, sys, urllib.request
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "public", "media", "products", "cutouts")
DATA = os.path.join(ROOT, "src", "data", "product-cutouts.data.js")
PAPER = (241, 229, 224)
MAX_H = 900


def photo_id(url):
    """Square photo URLs look like https://items-images-production.s3…/files/<40 hex>/original.jpeg."""
    match = re.search(r"/files/([0-9a-f]{20,64})/", url or "")
    return match.group(1) if match else None


def download(url):
    request = urllib.request.Request(url, headers={"User-Agent": "product-cutouts"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return Image.open(io.BytesIO(response.read())).convert("RGB")


def checks(original, cut):
    """Plain-language flags for a cut-out that should be looked at."""
    flags = []
    alpha = cut.getchannel("A")
    hist = alpha.histogram()
    total = original.width * original.height
    solid = sum(hist[236:])
    soft = sum(hist[21:236])
    if solid < total * 0.03:
        flags.append("product mostly lost")
    if solid > total * 0.85:
        flags.append("backdrop kept")
    if solid and soft > solid * 0.18:
        flags.append("soft or halo edges")
    box = alpha.point(lambda v: 255 if v > 20 else 0).getbbox()
    if box and (box[0] <= 1 or box[1] <= 1 or box[2] >= cut.width - 1 or box[3] >= cut.height - 1):
        flags.append("touches the photo's edge")
    return flags


def trim(cut):
    box = cut.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    if box:
        cut = cut.crop(box)
    if cut.height > MAX_H:
        cut = cut.resize((max(1, round(cut.width * MAX_H / cut.height)), MAX_H), Image.LANCZOS)
    return cut


def contact_sheet(entries, path):
    cell, label = 220, 34
    cols = 6
    rows = (len(entries) + cols - 1) // cols or 1
    sheet = Image.new("RGB", (cols * cell, rows * (cell + label)), "white")
    draw = ImageDraw.Draw(sheet)
    for index, entry in enumerate(entries):
        x, y = (index % cols) * cell, (index // cols) * (cell + label)
        tile = Image.new("RGB", (cell - 6, cell - 6), PAPER)
        image = Image.open(os.path.join(OUT_DIR, f"{entry['id']}.webp")).convert("RGBA")
        image.thumbnail((cell - 36, cell - 36))
        ox, oy = (tile.width - image.width) // 2, (tile.height - image.height) // 2
        shadow = Image.new("RGBA", tile.size, (0, 0, 0, 0))
        dark = Image.new("RGBA", image.size, (60, 40, 30, 255))
        dark.putalpha(image.getchannel("A").point(lambda v: v * 0.3))
        shadow.paste(dark, (ox + 3, oy + 7), dark)
        tile.paste(shadow.filter(ImageFilter.GaussianBlur(6)), (0, 0), shadow.filter(ImageFilter.GaussianBlur(6)))
        tile.paste(image, (ox, oy), image)
        sheet.paste(tile, (x + 3, y + 3))
        if entry["flags"]:
            draw.rectangle([x + 2, y + 2, x + cell - 3, y + cell - 3], outline=(200, 40, 40), width=3)
        draw.text((x + 4, y + cell), entry["name"][:34], fill=(30, 30, 30))
        draw.text((x + 4, y + cell + 14), ", ".join(entry["flags"])[:40] or "ok", fill=(200, 40, 40) if entry["flags"] else (90, 120, 90))
    sheet.save(path)


def write_data(entries):
    lines = [
        "// Generated by scripts/product-cutouts.py: the shop photos that have a cut-out",
        "// (background removed) in public/media/products/cutouts/<photo id>.webp.",
        "// Run the script again to add new products; don't edit by hand.",
        "export const CUTOUTS = {",
    ]
    for entry in sorted(entries, key=lambda e: e["id"]):
        name = entry["name"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  "{entry["id"]}": {{ name: "{name}", w: {entry["w"]}, h: {entry["h"]} }},')
    lines.append("};")
    with open(DATA, "w") as f:
        f.write("\n".join(lines) + "\n")


def existing_entries():
    if not os.path.exists(DATA):
        return {}
    entries = {}
    for match in re.finditer(r'"([0-9a-f]+)": \{ name: "((?:[^"\\]|\\.)*)", w: (\d+), h: (\d+) \}', open(DATA).read()):
        entries[match.group(1)] = {"id": match.group(1), "name": match.group(2).replace('\\"', '"'), "w": int(match.group(3)), "h": int(match.group(4)), "flags": []}
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("products", help="JSON list of {name, image} (from npm run products:list)")
    parser.add_argument("--model", default="isnet-general-use", help="rembg model (isnet-general-use, birefnet-general-lite…)")
    parser.add_argument("--redo", action="store_true", help="cut photos that already have a cut-out again")
    parser.add_argument("--skip", action="append", default=[], help="photo id to leave out (keeps the original in guides)")
    parser.add_argument("--sheet", default="cutouts-contact-sheet.png", help="where to save the contact sheet")
    args = parser.parse_args()

    from rembg import new_session, remove
    session = new_session(args.model)
    os.makedirs(OUT_DIR, exist_ok=True)
    products = json.load(open(args.products))
    entries = existing_entries()
    for skipped in args.skip:
        entries.pop(skipped, None)
        path = os.path.join(OUT_DIR, f"{skipped}.webp")
        if os.path.exists(path):
            os.remove(path)
    done = failed = 0
    for product in products:
        key = photo_id(product.get("image"))
        if not key or key in args.skip or (key in entries and not args.redo):
            continue
        try:
            original = download(product["image"])
            cut = remove(original, session=session, post_process_mask=True)
            flags = checks(original, cut)
            cut = trim(cut)
            cut.save(os.path.join(OUT_DIR, f"{key}.webp"), "WEBP", quality=88, method=6)
            entries[key] = {"id": key, "name": product["name"], "w": cut.width, "h": cut.height, "flags": flags}
            done += 1
            print(f"{'CHECK' if flags else 'ok   '} {product['name']}: {', '.join(flags) or 'clean'}")
        except Exception as error:  # one bad photo shouldn't stop the rest
            failed += 1
            print(f"FAIL  {product.get('name')}: {error}", file=sys.stderr)
    write_data(entries.values())
    new = [entry for entry in entries.values() if "flags" in entry]
    contact_sheet(sorted(new, key=lambda e: (not e["flags"], e["name"])), args.sheet)
    flagged = sum(1 for entry in entries.values() if entry["flags"])
    print(f"\n{done} cut, {failed} failed, {len(entries)} in total, {flagged} to look at. Contact sheet: {args.sheet}")


if __name__ == "__main__":
    main()
